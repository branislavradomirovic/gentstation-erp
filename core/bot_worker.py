def _now() -> float:
    return time.time()


def _safe_json(value: Any) -> str:
    return json.dumps(value, separators=(",", ":"), ensure_ascii=False)


def _ps_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except OSError:
        return False

    # Detect zombie processes via ps
    try:
        stat = subprocess.check_output(
            ["ps", "-p", str(pid), "-o", "stat="],
            text=True,
        ).strip()
        if not stat:
            return False
        if stat.upper().startswith("Z"):
            return False
    except Exception:
        pass

    return True


def acquire_lock() -> bool:
    """Create a stale-safe lock file to avoid duplicate bot/worker launches."""
    try:
        fd = os.open(str(LOCK_FILE), os.O_CREAT | os.O_EXCL | os.O_WRONLY)
        with os.fdopen(fd, "w") as fh:
            fh.write(str(os.getpid()))
        return True
    except FileExistsError:
        try:
            existing_pid = int(LOCK_FILE.read_text().strip() or "0")
            if _ps_alive(existing_pid):
                logger.error("Process already running with PID %s", existing_pid)
                return False
        except Exception:
            pass

        with suppress(Exception):
            LOCK_FILE.unlink()
        return acquire_lock()


def release_lock() -> None:
    try:
        if LOCK_FILE.exists():
            existing_pid = int(LOCK_FILE.read_text().strip() or "0")
            if existing_pid == os.getpid():
                LOCK_FILE.unlink()
    except Exception:
        pass


atexit.register(release_lock)


def _is_video_document(message) -> bool:
    document = getattr(message, "document", None)
    if not document:
        return False
    mime_type = (document.mime_type or "").lower()
    name = (document.file_name or "").lower()
    return mime_type.startswith(ALLOWED_MIME_PREFIXES) or mime_type in ALLOWED_MIME_TYPES or name.endswith(tuple(ALLOWED_VIDEO_SUFFIXES))


def _guess_suffix(filename: str | None, fallback: str = ".mp4") -> str:
    if not filename:
        return fallback
    suffix = Path(filename).suffix.lower()
    return suffix if suffix in ALLOWED_VIDEO_SUFFIXES else fallback


def _validate_video_file(file_name: str | None, mime_type: str | None) -> bool:
    suffix_ok = _guess_suffix(file_name) in ALLOWED_VIDEO_SUFFIXES
    mime = (mime_type or "").lower()
    mime_ok = mime.startswith(ALLOWED_MIME_PREFIXES) or mime in ALLOWED_MIME_TYPES
    return suffix_ok or mime_ok


