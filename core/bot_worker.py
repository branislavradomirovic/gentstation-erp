async def build_application() -> Application:
    if not TOKEN:
        raise RuntimeError("TELEGRAM_BOT_TOKEN not found in environment")

    app = ApplicationBuilder().token(TOKEN).build()
    app.add_handler(CommandHandler("start", start))
    media_filter = (
        filters.VIDEO
        | filters.Document.VIDEO
        | filters.Document.MimeType("video/mp4")
        | filters.Document.MimeType("video/quicktime")
        | filters.Document.MimeType("video/webm")
        | filters.Document.MimeType("video/x-matroska")
    )
    app.add_handler(MessageHandler(media_filter, handle_media))
    app.add_error_handler(error_handler)
    return app


async def run_bot_once() -> None:
    if not TOKEN:
        logger.error("TELEGRAM_BOT_TOKEN not found in .env")
        await update_bot_status("offline", "missing TELEGRAM_BOT_TOKEN")
        return

    app = await build_application()
    bot_running_event.set()
    await update_bot_status("starting")

    await app.initialize()
    await app.start()
    await app.updater.start_polling(drop_pending_updates=True)
    logger.info("Telegram bot is running.")

    try:
        await shutdown_event.wait()
    finally:
        bot_running_event.clear()
        with suppress(Exception):
            await app.updater.stop()
        with suppress(Exception):
            await app.stop()
        with suppress(Exception):
            await app.shutdown()
        await update_bot_status("stopped")


async def run_bot_with_retry() -> None:
    retry_delay = max(1, RETRY_BASE_SECONDS)

    while not shutdown_event.is_set():
        try:
            await run_bot_once()
            retry_delay = RETRY_BASE_SECONDS

            if shutdown_event.is_set():
                break

            logger.warning("Bot stopped unexpectedly. Restarting in %s sec...", retry_delay)

        except (NetworkError, TimedOut, RetryAfter) as e:
            logger.error("Network error: %s", e)

        except TelegramError as e:
            logger.error("Telegram API error: %s", e)

        except Exception as e:
            logger.exception("Bot crashed: %s", e)

        await asyncio.sleep(retry_delay)
        retry_delay = min(RETRY_MAX_SECONDS, retry_delay * 2)


async def run_both() -> None:
    tasks = []
    if BOT_MODE in {"bot", "both"}:
        tasks.append(asyncio.create_task(run_bot_with_retry(), name="telegram-bot"))
    if BOT_MODE in {"worker", "both"}:
        tasks.append(asyncio.create_task(worker_loop(), name="queue-worker"))
    tasks.append(asyncio.create_task(heartbeat_loop(), name="heartbeat"))
    tasks.append(asyncio.create_task(cleanup_old_uploads(), name="cleanup"))

    try:
        await asyncio.gather(*tasks)
    finally:
        for t in tasks:
            t.cancel()
        with suppress(Exception):
            await asyncio.gather(*tasks, return_exceptions=True)


def _install_signal_handlers(loop: asyncio.AbstractEventLoop) -> None:
    def _stop(*_: Any) -> None:
        shutdown_event.set()

    for sig_name in ("SIGINT", "SIGTERM"):
        sig = getattr(signal, sig_name, None)
        if sig is None:
            continue
        with suppress(NotImplementedError, RuntimeError):
            loop.add_signal_handler(sig, _stop)


