@dataclass
class SubmissionJob:
    job_id: str
    chat_id: str
    employee_id: int
    station_id: int
    file_path: str
    original_file_name: str
    size_bytes: int
    created_ts: float

    def to_redis_mapping(self) -> dict[str, str]:
        d = asdict(self)
        return {k: str(v) for k, v in d.items()}

    @staticmethod
    def from_redis_mapping(mapping: dict[str, Any]) -> "SubmissionJob":
        def _get(key: str, default: Any = None) -> Any:
            v = mapping.get(key, default)
            if isinstance(v, bytes):
                return v.decode("utf-8")
            return v

        return SubmissionJob(
            job_id=str(_get("job_id")),
            chat_id=str(_get("chat_id")),
            employee_id=int(_get("employee_id")),
            station_id=int(_get("station_id")),
            file_path=str(_get("file_path")),
            original_file_name=str(_get("original_file_name", "")),
            size_bytes=int(_get("size_bytes", 0)),
            created_ts=float(_get("created_ts", time.time())),
        )


