async def db_fetch_employee_by_chat(chat_id: str) -> Optional[tuple[int, Optional[int]]]:
    def _work():
        conn = None
        try:
            conn = get_connection()
            cur = conn.cursor()
            row = cur.execute(
                "SELECT id, station_id FROM employees WHERE telegram_chat_id = %s",
                (chat_id,),
            ).fetchone()
            return row
        finally:
            if conn:
                with suppress(Exception):
                    conn.close()

    return await asyncio.to_thread(_work)


