async def process_job(redis: Redis, stream_id: str, job: SubmissionJob) -> None:
    await update_job_status(job.file_path, "processing")

    def _simulate_or_run_heavy_task() -> None:
        return None

    try:
        await asyncio.to_thread(_simulate_or_run_heavy_task)
        await update_job_status(job.file_path, "done")
        logger.info("Processed job %s (stream id %s)", job.job_id, stream_id)
    except Exception as e:
        await update_job_status(job.file_path, "failed")
        raise


async def worker_loop() -> None:
    redis = await get_redis()
    await ensure_stream_group(redis)
    consumer_name = os.getenv("QUEUE_CONSUMER") or f"{socket.gethostname()}-{os.getpid()}"

    while not shutdown_event.is_set():
        try:
            entries = await redis.xreadgroup(
                groupname=QUEUE_GROUP,
                consumername=consumer_name,
                streams={QUEUE_STREAM: ">"},
                count=10,
                block=5000,
            )

            if not entries:
                continue

            for _stream_name, messages in entries:
                for stream_id, mapping in messages:
                    try:
                        job = SubmissionJob.from_redis_mapping(mapping)
                        await process_job(redis, stream_id, job)
                        await redis.xack(QUEUE_STREAM, QUEUE_GROUP, stream_id)
                    except Exception as e:
                        logger.exception("Worker failed for stream id %s: %s", stream_id, e)
                        # Leave unacked for retry / inspection. You can add DLQ handling here.
        except asyncio.CancelledError:
            break
        except Exception as e:
            logger.error("Worker loop error: %s", e)
            try:
                await asyncio.wait_for(shutdown_event.wait(), timeout=5)
            except asyncio.TimeoutError:
                pass


